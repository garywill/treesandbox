def deploy_sandbox(sbx):
    if sbx.destfile:
        destfile = sbx.destfile
        if not destfile.lower().endswith('.py'):
            raise Exception("destfile should end with '.py'")
    elif sbx.destdir:
        destfile = f'{sbx.destdir}/tsbxrun_{sbx.name}.py'
    else:
        raise Exception("No destdir nor destfile")

    uc_filename = f'uc.{sbx.name}.py'
    uc_file_path = f'{user_sbxes_path}/{uc_filename}'
    if not os.path.exists(uc_file_path):
        log_warn(f'✘ User config file not exist {uc_file_path} . Skip {sbx}')
        return False
    if not check_pyfile_syntax(uc_file_path):
        log_warn(f'✘ Syntax error in file {uc_file_path}. Skip {sbx}')
        return False

    destdir = os.path.dirname(destfile)
    if not os.path.exists(destdir):
        log(f'Dir {destdir} not exist. Skip {sbx}.')
        return False

    if os.path.exists(destfile) and os.stat(destfile).st_size > 0:
        if not 'Tree Sandbox' in open(destfile).read(800):
            log_warn(f'✘ Target file {destfile} already exists and its content seems not to be a script of Tree Sandbox. Skip {sbx} . Please manually check and remove it if needed.')
            return False

    code_content = make_tsbx_code(uc_file_path)

    with open(destfile, 'w') as f:
        f.write(code_content)
        os.chmod(f.name, 0o755)
    log(f'Write to {destfile} done.')

def make_tsbx_code(uc_file_path):
    uc_file_content = open(uc_file_path).read()

    full_code = f'''#!/usr/bin/env -S {sys.executable} -IBS
{BEFORE}

# !! NOTE Do NOT modify this file here. This file is auto generated by deploy script of TreeSandbox. The uc.<name>.py config file is the userconfig source. !!

{uc_file_content}
{AFTER}
    '''
    return full_code

BEFORE = None
AFTER = None
def prepare():
    global BEFORE, AFTER
    TSBX_ORIG_CODE_FILEPATH = f'{scriptpadirpath}/treesandbox.py'
    TSBX_ORIG_CONTENT = open(TSBX_ORIG_CODE_FILEPATH).read()
    TSBXS_LINES = TSBX_ORIG_CONTENT.splitlines()

    start_marker = "# === USER_CONFIG BEGIN ==="
    end_marker =   "# === USER_CONFIG END ==="

    start_index = None
    end_index = None

    for i, line in enumerate(TSBXS_LINES):
        if line.startswith(start_marker):
            start_index = i
        elif line.startswith(end_marker):
            end_index = i
        if start_index is not None and end_index is not None:
            break
    if start_index is None:
        log_warn(f"✘ Failed find start mark '{start_marker}' in {TSBX_ORIG_CODE_FILEPATH}")
        sys.exit(1)
    if end_index is None:
        log_warn(f"✘ Failed find end mark '{end_marker}' in {TSBX_ORIG_CODE_FILEPATH}")
        sys.exit(1)
    if not (start_index < end_index):
        log_warn(f'✘ Start mark and end mark have wrong sequence in {TSBX_ORIG_CODE_FILEPATH}')
        sys.exit(1)

    BEFORE = '\n'.join( TSBXS_LINES[:start_index+1] )
    AFTER = '\n'.join( TSBXS_LINES[end_index:] )
    # AFTER = '\n\n' + TSBXS_LINES[end_index] + '\n\n' + ast.unparse(ast.parse(AFTER)) # Don't minimize. That'll make error message a mess

    if not check_pycode_syntax(BEFORE):
        log_warn('Syntax error detected in the head of treesandbox.py')
        sys.exit(1)
    if not check_pycode_syntax(AFTER):
        log_warn('Syntax error detected in the body of treesandbox.py')
        sys.exit(1)


def check_pyfile_syntax(filepath):
    try:
        ast.parse(open(filepath).read())
        return True
    except SyntaxError as e:
        print(f"❌ Syntax Error in {filepath}:")
        print(f"   Line {e.lineno}, Col {e.offset}: \n{e.text if e.text else ''}")
        print(f"   Err msg: {e.msg}")
        return False

def check_pycode_syntax(codecontent):
    try:
        ast.parse(codecontent)
        return True
    except SyntaxError as e:
        print(f"❌ Syntax Error:")
        print(f"   Line {e.lineno}, Col {e.offset}: \n{e.text if e.text else ''}")
        print(f"   Err msg: {e.msg}")
        return False



